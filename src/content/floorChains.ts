/**
 * 月度全樓事件鏈的**純資料**檔(零 sim import,只吃型別)。
 *
 * 邏輯(挑鏈/推進/收束/結算)一律留在 `src/sim/floorChain.ts`;本檔只放章節文本與數值,
 * 之後補文本 = 只改這裡,sim 測試與 balance 快照都不會被碰到。
 *
 * 🔴 硬性約束(見 docs/待辦.md 第四節):
 * - `id` 會進存檔(`state.floorChain.chainId`),既有鏈的 id 一個字都不能改
 * - 每條鏈 **4 階段 × 每階段 3 個選項**,且剛好一個階段掛房東抉擇
 * - 每階段的抉擇必含三種型態:花錢買最好結果($900~$3,000)/不花錢出力(bond 高)/擺爛(負值但可回復)
 * - 數值幅度:satisfaction ±8、affinity ±6、stress ±6(擺爛可到 +6)、mood ±8、bond 0~4
 * - `notices` 是**旁白變體池**(2~3 句),由 sim 端決定性雜湊挑一句,避免同一條鏈重跑逐字重複
 */
import type { GroupChoice, GroupDelta } from "../types";
import type { GroupSceneLayout } from "../floor/groupScene";

export interface ChainStage {
  /** 這一話的標題(章節卡列出) */
  title: string;
  /** 全樓公告(進通知歷史與動態 Feed);同時是旁白變體池的第一句 */
  notice: string;
  /**
   * 旁白變體(2~3 句):與 `notice` 合成一個池,由 sim 端依「鏈 id + 話數 + 開章日」
   * 決定性挑一句,讓同一條鏈第二次跑到時不會逐字重複。
   * 🔴 只能**追加**,不可改寫既有的 `notice`(它是抽檔前就存在的字面值)。
   */
  notices?: string[];
  /** 在場租客的個人日誌文案池(決定性挑一句) */
  lines: string[];
  /** 對在場租客的數值影響 */
  effect?: GroupDelta;
  /** 在場租客兩兩關係變化 */
  bond?: number;
  /** 這一話掛出的伏筆旗標(純中文,可安全當 AI 敘事素材) */
  flag?: string;
  /** 交誼廳特效(讓事發地看得到) */
  fx?: "chat" | "anger" | "lights";
  /** 明確寫到大家聚在交誼廳的話，接管參與者走位並顯示現場標題。 */
  scene?: { layout: GroupSceneLayout };
  /** 這一話要房東抉擇(掛上 state.pendingChainEvent) */
  decision?: { title: string; description: string; choices: GroupChoice[] };
}

export interface ChainDef {
  id: string;
  icon: string;
  title: string;
  stages: ChainStage[];
}

